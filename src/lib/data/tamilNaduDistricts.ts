export function getDistrictById(id: string): DistrictMetadata | undefined {
  const norm = id.toLowerCase().trim().replace(/\s+/g, '-');
  return TAMIL_NADU_DISTRICTS.find(d => d.id === norm || d.name.toLowerCase() === id.toLowerCase());
}


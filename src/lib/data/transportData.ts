export function getTransportKPI(operators: TransportRecord[] = TRANSPORT_OPERATORS): TransportKPI {
  const total_fleets = operators.length;
  const bus_services = operators.filter(o => o.service_type === 'bus').length;
  const lorry_services = operators.filter(o => o.service_type === 'lorry' || o.service_type === 'logistics').length;
  const verified_owners = operators.filter(o => Boolean(o.owner_name && o.owner_name.length > 2)).length;
  const whatsapp_verified = operators.filter(o => Boolean(o.whatsapp_number && o.whatsapp_number.length >= 10)).length;
  const email_verified = operators.filter(o => Boolean(o.email && o.email.includes('@'))).length;
  const districtSet = new Set(operators.map(o => o.district.toLowerCase()));
  const national_permits = operators.filter(o => o.permit_type.includes('National') || o.permit_type.includes('All India')).length;
  
  // Total regional branches count
  const total_branches_count = operators.reduce((acc, curr) => acc + (curr.branches ? curr.branches.length : 0), 0);

  return {
    total_fleets,
    bus_services,
    lorry_services,
    verified_owners,
    whatsapp_verified,
    email_verified,
    districts_covered: districtSet.size,
    national_permits,
    total_branches_count
  };
}
